"""Generates a CycloneDX 1.5 SBOM (JSON) and a third-party license table for the shipped binaries.

Only normal (non-dev, non-build-only) dependencies reachable from omnidecomp-cli and omnidecomp-gui are
included, because those are what a release contains. Source of truth: `cargo metadata` plus the checksums
in Cargo.lock. Offline; uses only the Python standard library.

    python -I scripts/sbom.py [--out dist/omnidecomp.cdx.json] [--licenses dist/THIRD_PARTY_LICENSES.md]
"""
import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHIPPED = ("omnidecomp-cli", "omnidecomp-gui")


def cargo_metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


def lock_checksums():
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text(encoding="utf-8"))
    return {(p["name"], p["version"]): p.get("checksum") for p in lock["package"]}


def shipped_closure(meta):
    """Package ids reachable through normal dependency edges from the shipped binaries."""
    by_name = {p["name"]: p["id"] for p in meta["packages"] if p["id"] in meta["workspace_members"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, stack = set(), [by_name[n] for n in SHIPPED]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return seen


def purl(p):
    return f"pkg:cargo/{p['name']}@{p['version']}"


def spdx_expr(lic):
    # Cargo uses "/" as an old spelling of OR.
    return (lic or "").replace("/", " OR ") if lic and " " not in lic else (lic or "")


def build(meta):
    ids = shipped_closure(meta)
    pkgs = sorted((p for p in meta["packages"] if p["id"] in ids), key=lambda p: (p["name"], p["version"]))
    sums = lock_checksums()
    workspace = set(meta["workspace_members"])
    components, license_rows, missing = [], [], []
    for p in pkgs:
        is_ws = p["id"] in workspace
        lic = p.get("license")
        comp = {
            "type": "application" if (is_ws and p["name"] in SHIPPED) else "library",
            "bom-ref": purl(p),
            "name": p["name"],
            "version": p["version"],
            "purl": purl(p),
        }
        if lic:
            comp["licenses"] = [{"expression": spdx_expr(lic)}]
        elif not is_ws:
            missing.append(p["name"])
        sha = sums.get((p["name"], p["version"]))
        if sha:
            comp["hashes"] = [{"alg": "SHA-256", "content": sha}]
        if p.get("repository"):
            comp["externalReferences"] = [{"type": "vcs", "url": p["repository"]}]
        components.append(comp)
        if not is_ws:
            license_rows.append((p["name"], p["version"], lic or "(none declared)"))
    ver = next(p["version"] for p in pkgs if p["name"] == "omnidecomp-cli")
    sbom = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "component": {"type": "application", "name": "OmniDecomp", "version": ver, "bom-ref": "omnidecomp"},
            "tools": {"components": [{"type": "application", "name": "scripts/sbom.py"}]},
        },
        "components": components,
    }
    return sbom, license_rows, missing


def write_licenses(path, rows, version):
    lines = [
        f"# OmniDecomp {version}: third-party components in the shipped binaries",
        "",
        "Generated by scripts/sbom.py from `cargo metadata` (normal dependencies of omnidecomp-cli and omnidecomp-gui).",
        "License texts are those published by each crate. Fonts bundled by egui (OFL-1.1, Ubuntu-font-1.0) are covered by",
        "THIRD_PARTY_NOTICES.md. Where a crate is dual-licensed, the permissive option is used.",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {l} |" for n, v, l in rows]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "dist" / "omnidecomp.cdx.json"))
    ap.add_argument("--licenses", default=str(ROOT / "dist" / "THIRD_PARTY_LICENSES.md"))
    args = ap.parse_args()
    meta = cargo_metadata()
    sbom, rows, missing = build(meta)
    out, lic = Path(args.out), Path(args.licenses)
    out.parent.mkdir(parents=True, exist_ok=True)
    lic.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(sbom, indent=2) + "\n", encoding="utf-8", newline="\n")
    write_licenses(lic, rows, sbom["metadata"]["component"]["version"])
    print(f"components: {len(sbom['components'])} ({len(rows)} third-party)")
    print(f"sbom: {out}\nlicenses: {lic}")
    if missing:
        print("ERROR: components without a declared license: " + ", ".join(missing), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
